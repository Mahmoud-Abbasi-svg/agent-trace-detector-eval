def get(path):
    cur = R
    for p in path.split("."):
        cur = cur[int(p)] if isinstance(cur, list) else cur[p]
    return cur


def f3(x):
    return "n/a" if x is None else f"{x:.3f}"


def ci(path, d=3):
    """'point [lo, hi]' from a [point, lo, hi] triple, with its key."""
    v = get(path)
    fmt = (lambda x: f"{x:.{d}f}")
    return f"{fmt(v[0])} [{fmt(v[1])}, {fmt(v[2])}] (`{path}`)"


def cis(path, d=3):
    """signed difference 'point [lo, hi]' plus the share of replicates <= 0."""
    v = get(path)
    fmt = (lambda x: f"{x:+.{d}f}")
    return f"{fmt(v[0])} [{fmt(v[1])}, {fmt(v[2])}] (`{path}`)"


def val(path, fmt="{}"):
    return f"{fmt.format(get(path))} (`{path}`)"


def num(path):
    v = get(path)
    return f"{v:,}" if isinstance(v, int) else str(v)


